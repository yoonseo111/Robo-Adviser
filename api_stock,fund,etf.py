    "AAPL", "MSFT", "GOOGL", "AMZN", "FB", "TSLA", "NFLX",
    "INTC", "NVDA", "PYPL", "CSCO", "CMCSA", "PEP", "ADBE",
    "AMGN", "AVGO", "TXN", "COST", "QCOM", "V"
