import yfinance as yf
import pandas as pd

def get_stocks_info(tickers):
    # 종목 정보를 저장할 데이터 프레임 생성
    stocks_info = pd.DataFrame()

    # 각 종목에 대한 정보 조회
    for ticker in tickers:
        stock = yf.Ticker(ticker)
        info = stock.info

        # 최근 종가 조회
        history = stock.history(period="1d")  # 가장 최근 거래일 데이터
        recent_close = history['Close'].iloc[-1] if not history.empty else None

        # 필요한 정보만 추출
        stock_data = {
            'Ticker': ticker,
            'Name': info.get('longName'),
            'Sector': info.get('sector'),
            'Industry': info.get('industry'),
            'Market Cap': info.get('marketCap'),
            'Price': recent_close,  # 최근 종가로 업데이트
            'Forward PE': info.get('forwardPE'),
            'Dividend Yield': info.get('dividendYield')  # 배당 수익률
        }
        # 데이터 프레임에 추가
        stock_data_df = pd.DataFrame([stock_data])
        stocks_info = pd.concat([stocks_info, stock_data_df], ignore_index=True)

    return stocks_info

def save_to_csv(tickers, filename='stocks_info.csv'):
    # 주식 정보 조회
    stocks_info_df = get_stocks_info(tickers)
    # CSV 파일로 저장
    stocks_info_df.to_csv(filename, index=False)
    print(f"Data saved to {filename}")

# 예시 종목 리스트
