def get_recent_business_day():
    today = datetime.today()
    offset = 30  # 과거 30일 간 검색
    for i in range(offset):
        # 과거로 거슬러 올라가며 거래일 확인
        test_day = today - timedelta(days=i)
        formatted_day = test_day.strftime("%Y%m%d")
        # 해당 날짜에 주식 시장 데이터가 존재하는지 확인
        if not stock.get_market_ohlcv_by_date(formatted_day, formatted_day, "005930").empty:
            return formatted_day
    return None  # 30일 내에 거래일이 없으면 None 반환

def get_recent_stock_info(tickers):
    # 가장 최근의 거래일을 얻기
    recent_date = get_recent_business_day()
    if not recent_date:
        return pd.DataFrame()  # 최근 거래일을 찾지 못한 경우

    # 모든 주식 정보를 저장할 데이터프레임
    all_stocks = pd.DataFrame()

    # 주어진 모든 티커에 대해 정보를 수집
    for ticker in tickers:
        df = stock.get_market_ohlcv_by_date(recent_date, recent_date, ticker)
        if not df.empty:
            df['Ticker'] = ticker  # 종목코드 추가
            all_stocks = pd.concat([all_stocks, df])

    return all_stocks

