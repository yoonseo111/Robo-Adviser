import numpy as np

# 감성 분석 점수 생성 (0: 부정, 1: 긍정)
def generate_sentiment_scores(data):
    return np.random.choice([0, 1], size=len(data)) # 지금은 random으로 설정

# 각 기업의 감성 점수 추가
for ticker, data in stock_data.items():
    data['Sentiment'] = generate_sentiment_scores(data)

import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense, Dropout
from sklearn.preprocessing import MinMaxScaler

# LSTM 모델을 위한 데이터 전처리
def prepare_data(data, n_steps=60):
    scaler = MinMaxScaler(feature_range=(0, 1))
    scaled_data = scaler.fit_transform(data[['Close']])

    X, y = [], []
    for i in range(n_steps, len(scaled_data)):
        X.append(scaled_data[i-n_steps:i, 0])
        y.append(scaled_data[i, 0])

    X = np.array(X)
    y = np.array(y)

    return X.reshape((X.shape[0], X.shape[1], 1)), y, scaler

# LSTM 모델 생성
def create_lstm_model(input_shape):
    model = Sequential()
    model.add(LSTM(units=50, return_sequences=True, input_shape=input_shape))
    model.add(Dropout(0.2))
    model.add(LSTM(units=50, return_sequences=False))
    model.add(Dropout(0.2))
    model.add(Dense(units=1))
    model.compile(optimizer='adam', loss='mean_squared_error')
    return model

# 모델 훈련 및 예측
def train_and_predict(data, n_steps=60):
    X, y, scaler = prepare_data(data, n_steps)
    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, shuffle=False)

    model = create_lstm_model((X_train.shape[1], 1))
    model.fit(X_train, y_train, epochs=10, batch_size=32)

    predicted_prices = model.predict(X_test)
    predicted_prices = scaler.inverse_transform(predicted_prices)

    return predicted_prices, scaler.inverse_transform(y_test.reshape(-1, 1))

# 각 기업에 대해 모델 훈련 및 예측
predictions = {}
for ticker, data in stock_data.items():
    predicted, actual = train_and_predict(data)
    predictions[ticker] = (predicted, actual)

