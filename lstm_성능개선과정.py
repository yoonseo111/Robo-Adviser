# 추천 여부 판단 함수
def recommend_stock(predicted, actual, period=5):
    # 마지막 period 기간 동안의 평균 주가 변화 계산
    pred_diff = np.mean(predicted[-period:]) - np.mean(predicted[-(period*2):-period])
    actual_diff = np.mean(actual[-period:]) - np.mean(actual[-(period*2):-period])

    # 실제 주가와 예측 주가가 둘 다 상승세를 보이는지 확인
    if pred_diff > 0 and actual_diff > 0:
        print("추천: 최근 상승세를 보이고 있습니다.")
    else:
        print("비추천: 최근 상승세가 아닙니다.")

