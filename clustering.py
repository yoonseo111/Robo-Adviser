# 주식 상승률 계산 및 추천 함수
def calculate_stock_performance(ticker):
    stock = yf.Ticker(ticker)
    end_date = datetime.now()
    start_date = end_date - timedelta(days=365)
    hist = stock.history(start=start_date, end=end_date)
    if len(hist) < 2:
        return 0  # 데이터가 충분하지 않으면 상승률 0으로 처리
    return (hist['Close'][-1] - hist['Close'][0]) / hist['Close'][0]

def recommend_stocks(interest):
    tickers = stock_tickers.get(interest, [])
    performances = []
    for ticker in tickers:
        try:
            performance = calculate_stock_performance(ticker)
            performances.append((ticker, performance))
        except Exception as e:
            continue  # 오류가 발생하면 해당 주식 무시
    performances.sort(key=lambda x: x[1], reverse=True)
    top_3 = [ticker for ticker, _ in performances[:3]]
    return ", ".join(top_3)

# 클러스터 2 사용자에 대한 주식 추천 생성
cluster_2_users['추천 종목'] = cluster_2_users['관심분야'].apply(recommend_stocks)

