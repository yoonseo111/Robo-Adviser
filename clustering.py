import pandas as pd
from sklearn.preprocessing import OneHotEncoder
from sklearn.cluster import KMeans
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.decomposition import TruncatedSVD
import matplotlib.pyplot as plt
import numpy as np

# Load the generated data
file_path = '/content/drive/MyDrive/4-1 한이음/user.xlsx'
df = pd.read_excel(file_path)

# 아이디 칼럼 삭제
df_features = df.drop(columns=['아이디'])

# 투자성형 칼럼을 반복함으로써 가중치 부여
weighted_df_features = df_features.copy()
for i in range(4):  # 4번 반복
    weighted_df_features[f'투자성향_{i}'] = df_features['투자성향']

# 원-핫 인코딩 수행
preprocessor = ColumnTransformer(
    transformers=[
        ('cat', OneHotEncoder(), weighted_df_features.columns)
    ],
    remainder='passthrough'
)

# 파이프라인 구축
pipeline = Pipeline([
    ('preprocessor', preprocessor),
    ('kmeans', KMeans(n_clusters=4, random_state=42))
])

# 파이프라인 학습
pipeline.fit(weighted_df_features)

# 클러스터 생성 후 칼럼 추가
df['Cluster'] = pipeline.predict(weighted_df_features)

svd = TruncatedSVD(n_components=2, random_state=42)
df_svd = svd.fit_transform(pipeline.named_steps['preprocessor'].transform(weighted_df_features))

# Create a scatter plot
plt.figure(figsize=(10, 7))
for cluster in range(4):
    plt.scatter(df_svd[df['Cluster'] == cluster][:, 0], df_svd[df['Cluster'] == cluster][:, 1], label=f'Cluster {cluster}')

plt.xlabel('SVD Component 1')
plt.ylabel('SVD Component 2')
plt.title('Clusters Visualization with Weighted Investment Tendency')
plt.legend()
plt.show()

# Get the cluster centers
cluster_centers_weighted = pipeline.named_steps['kmeans'].cluster_centers_

# Reverse the one-hot encoding to get the original feature values
encoder = pipeline.named_steps['preprocessor'].named_transformers_['cat']
feature_names = encoder.get_feature_names_out(weighted_df_features.columns)

# Decode the one-hot encoded features
decoded_centers_weighted = encoder.inverse_transform(cluster_centers_weighted)

# Create a DataFrame for decoded cluster centers
decoded_centers_df_weighted = pd.DataFrame(decoded_centers_weighted, columns=weighted_df_features.columns)

# Save the cluster centers to an Excel file for further analysis
output_file_path_weighted = '/content/drive/MyDrive/4-1 한이음/user_weighted.xlsx'
decoded_centers_df_weighted.to_excel(output_file_path_weighted, index=False)

